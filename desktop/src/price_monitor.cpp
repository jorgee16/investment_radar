void Monitor::sql(const char* s){
    if(sqlite3_exec(db,s,nullptr,nullptr,nullptr)!=SQLITE_OK)
        throw std::runtime_error("Monitor transaction failed");
}
Monitor::Monitor(const std::string& path){
    if(sqlite3_open(path.c_str(),&db)!=SQLITE_OK){
        if(db)sqlite3_close(db);
        db=nullptr;
        throw std::runtime_error("Cannot open monitor database");
    }
    sqlite3_busy_timeout(db,5000);
    sql("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL;");
    Stmt version(db,"PRAGMA user_version");
    version.row();
    const int schema=sqlite3_column_int(version.p,0);
    if(schema>2)throw std::runtime_error("Monitor database requires newer application");
    sql("BEGIN IMMEDIATE");
    try {
        if(schema==0){
            sql("CREATE TABLE IF NOT EXISTS alert_rules(id TEXT PRIMARY KEY,body TEXT NOT NULL);"
                "CREATE TABLE IF NOT EXISTS alert_events(id TEXT PRIMARY KEY,body TEXT NOT NULL);"
                "CREATE TABLE IF NOT EXISTS delivery_outbox("
                "id TEXT PRIMARY KEY,body TEXT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,"
                "due INTEGER NOT NULL DEFAULT 0,status TEXT NOT NULL DEFAULT 'pending',lease TEXT);"
                "CREATE TABLE IF NOT EXISTS delivery_attempts(id TEXT,at INTEGER,accepted INTEGER);");
        }
        if(schema==1)
            sql("ALTER TABLE delivery_outbox ADD COLUMN lease TEXT;");
        sql("CREATE TABLE IF NOT EXISTS latest_quotes("
            "instrument TEXT PRIMARY KEY,body TEXT NOT NULL);"
            "PRAGMA user_version=2;");
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
}
Monitor::~Monitor(){if(db)sqlite3_close(db);}
json Monitor::snapshot(){
    std::lock_guard lock(mu);
    json j={{"health",health},{"instruments",instruments()},{"rules",json::array()},
            {"events",json::array()},{"deliveries",json::array()},
            {"quotes",json::array()}};
    for(auto table:{"alert_rules","alert_events","latest_quotes"}){
        std::string query="SELECT body FROM "+std::string(table)+" ORDER BY rowid DESC LIMIT 200";
        Stmt s(db,query.c_str());
        const char* key=std::string(table)=="alert_rules"?"rules":
                        std::string(table)=="alert_events"?"events":"quotes";
        while(s.row()){
            auto b=json::parse(s.str(0));
            if(std::string(table)=="latest_quotes"){
                const auto stamp=b.value("exchangeTime",int64_t{0});
                b["ageSeconds"]=stamp>0?json(std::time(nullptr)-stamp):json(nullptr);
                const auto lastStamp=b.value("lastTime",int64_t{0});
                b["lastAgeSeconds"]=lastStamp>0?json(std::time(nullptr)-lastStamp):json(nullptr);
            }
            j[key].push_back(b);
        }
    }
    Stmt d(db,"SELECT id,status,attempts FROM delivery_outbox ORDER BY rowid DESC LIMIT 100");
    while(d.row())j["deliveries"].push_back(
        {{"id",d.str(0)},{"status",d.str(1)},{"attempts",sqlite3_column_int(d.p,2)}});
    return j;
}
json Monitor::save(const json& j){
    std::lock_guard lock(mu);
    Rule r=parseRule(j);
    sql("BEGIN IMMEDIATE");
    try {
        if(r.id.empty()){
            Stmt s(db,"SELECT lower(hex(randomblob(16)))");s.row();r.id=s.str(0);
        }else{
            Stmt old(db,"SELECT body FROM alert_rules WHERE id=?");
            old.text(1,r.id);
            if(!old.row())throw std::invalid_argument("Unknown rule");
            r.generation=load(json::parse(old.str(0))).generation+1;
            cancelPending(db,r.id);
        }
        auto body=ruleJson(r);
        Stmt s(db,"INSERT OR REPLACE INTO alert_rules VALUES(?,?)");
        s.text(1,r.id);s.text(2,body.dump());s.row();
        sql("COMMIT");
        states.erase(r.id);
        return body;
    }catch(...){sql("ROLLBACK");throw;}
}
void Monitor::action(const std::string& id,const std::string& a){
    std::lock_guard lock(mu);
    sql("BEGIN IMMEDIATE");
    try {
        Stmt s(db,"SELECT body FROM alert_rules WHERE id=?");
        s.text(1,id);
        if(!s.row())throw std::invalid_argument("Unknown rule");
        auto r=load(json::parse(s.str(0)));
        if(a!="delete"&&a!="pause"&&a!="rearm")
            throw std::invalid_argument("Unknown action");
        cancelPending(db,id);
        if(a=="delete"){
            Stmt d(db,"DELETE FROM alert_rules WHERE id=?");
            d.text(1,id);d.row();
        }else{
            r.armed=a=="rearm";
            r.generation++;
            Stmt u(db,"UPDATE alert_rules SET body=? WHERE id=?");
            u.text(1,ruleJson(r).dump());u.text(2,id);u.row();
        }
        sql("COMMIT");
        states.erase(id);
    }catch(...){sql("ROLLBACK");throw;}
}
void Monitor::observe(const Quote& q,int64_t now){
    std::lock_guard lock(mu);
    // Display last observation with its true exchange age, even when it is stale.
    {
        Stmt u(db,"INSERT INTO latest_quotes VALUES(?,?) "
                  "ON CONFLICT(instrument) DO UPDATE SET body=excluded.body");
        u.text(1,q.instrument);u.text(2,quoteJson(q,now).dump());u.row();
    }
    health["lastReceived"]=now;
    health["instrument"]=q.instrument;
    health["exchangeTime"]=q.exchangeTime;
    health["venue"]=q.venue;health["feed"]=q.feed;
    health["session"]=q.session;health["delaySeconds"]=q.delaySeconds;
    Stmt s(db,"SELECT body FROM alert_rules");
    while(s.row()){
        auto r=load(json::parse(s.str(0)));
        if(r.instrument!=q.instrument)continue;
        auto result=evaluate(r,states[r.id],q,now);
        health["evaluation"]=result;
        if(result!="trigger")continue;
        const auto id=r.id+":"+std::to_string(r.generation);
        auto event=ruleJson(r);
        event["id"]=id;
        event["ruleId"]=r.id;
        event["observedAt"]=r.basis=="LAST"?q.lastTime:q.exchangeTime;event["receivedAt"]=now;
        event["priceUnits"]=r.basis=="ASK"?*q.ask:*q.last;
        event["delaySeconds"]=q.delaySeconds;event["session"]=q.session;
        sql("BEGIN IMMEDIATE");
        try {
            Stmt e(db,"INSERT OR IGNORE INTO alert_events VALUES(?,?)");
            e.text(1,id);e.text(2,event.dump());e.row();
            if(sqlite3_changes(db)){
                for(const auto channel:{"notification","email"}){
                    if(std::string(channel)=="email"&&r.email.empty())continue;
                    auto b=event;b["channel"]=channel;
                    Stmt o(db,"INSERT INTO delivery_outbox(id,body) VALUES(?,?)");
                    o.text(1,id+":"+channel);o.text(2,b.dump());o.row();
                }
            }
            r.armed=false;
            Stmt u(db,"UPDATE alert_rules SET body=? WHERE id=?");
            u.text(1,ruleJson(r).dump());u.text(2,r.id);u.row();
            sql("COMMIT");
        }catch(...){sql("ROLLBACK");states.erase(r.id);throw;}
    }
}
void Monitor::disconnect(const std::string& reason){
    std::lock_guard lock(mu);
    states.clear();
    health={{"status",reason}};
}
void Monitor::sourceHealth(const json& j){
    std::lock_guard lock(mu);
    health=j;
}
json Monitor::claim(int64_t now){
    std::lock_guard lock(mu);
    json rows=json::array();
    sql("BEGIN IMMEDIATE");
    try {
        // The fifth attempt may expire while the app is down: do not leave it 'sending' forever.
        {
            Stmt expire(db,"UPDATE delivery_outbox SET status='failed',lease=NULL "
                           "WHERE status='sending' AND due<=? AND attempts>=5");
            expire.num(1,now);expire.row();
        }
        Stmt s(db,"SELECT id,body FROM delivery_outbox "
                  "WHERE status IN ('pending','sending') AND due<=? AND attempts<5 "
                  "ORDER BY due,rowid LIMIT 10");
        s.num(1,now);
        while(s.row()){
            const auto id=s.str(0);
            Stmt token(db,"SELECT lower(hex(randomblob(16)))");token.row();
            const auto lease=token.str(0);
            Stmt u(db,"UPDATE delivery_outbox "
                      "SET status='sending',due=?,attempts=attempts+1,lease=? WHERE id=?");
            u.num(1,now+120);u.text(2,lease);u.text(3,id);u.row();
            auto b=json::parse(s.str(1));
            b["deliveryId"]=id;b["leaseToken"]=lease;
            rows.push_back(std::move(b));
        }
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
    return rows;
}
void Monitor::complete(const std::string& id,const std::string& lease,bool ok,int64_t now){
    std::lock_guard lock(mu);
    if(lease.empty())return; // Missing leases are never allowed to acknowledge a reissued job.
    sql("BEGIN IMMEDIATE");
    try {
        Stmt s(db,"UPDATE delivery_outbox "
                  "SET status=CASE WHEN ? THEN 'accepted' "
                  "WHEN attempts>=5 THEN 'failed' ELSE 'pending' END,"
                  "due=?+(30 << min(attempts,5)),lease=NULL "
                  "WHERE id=? AND status='sending' AND lease=?");
        s.num(1,ok);s.num(2,now);s.text(3,id);s.text(4,lease);s.row();
        if(sqlite3_changes(db)){
            Stmt a(db,"INSERT INTO delivery_attempts VALUES(?,?,?)");
            a.text(1,id);a.num(2,now);a.num(3,ok);a.row();
        }
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
}
