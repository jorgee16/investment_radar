// Register selected metadata only; user/provider catalog search is NOT entitlement proof.
// Any new listing is initially unverified regardless of caller-supplied 'source'.
json Monitor::registerInstrument(const json& input){
    std::lock_guard lock(mu);
    const std::string id=input.at("id").get<std::string>();
    const std::string name=input.at("name").get<std::string>();
    const std::string currency=input.at("currency").get<std::string>();
    const std::string mic=input.at("mic").get<std::string>();
    const std::string isin=input.value("isin",std::string());
    if(!validUpper(id,1,32,".^:-")||name.empty()||name.size()>120||
       name.find_first_of("\r\n")!=std::string::npos||
       !validUpper(currency,3,3)||!validUpper(mic,4,4)||
       (!isin.empty()&&!validUpper(isin,12,12)))
        throw std::invalid_argument("Invalid instrument identity");
    for(const auto& seed:instruments())if(seed["id"]==id){
        if(seed["currency"]!=currency||seed["mic"]!=mic||
           (!isin.empty()&&seed["isin"]!=isin))
            throw std::invalid_argument("Instrument identity conflicts with reference listing");
        return seed;
    }
    Stmt old(db,"SELECT body FROM registered_instruments WHERE id=?");
    old.text(1,id);
    if(old.row()){
        auto current=json::parse(old.str(0));
        if(current["currency"]!=currency||current["mic"]!=mic||
           current.value("isin","")!=isin)
            throw std::invalid_argument("Instrument already exists with a different listing");
        return current;
    }
    json item={{"id",id},{"name",name},{"currency",currency},{"mic",mic},
               {"isin",isin},{"source","unverified"},{"verification","catalog-selection-only"}};
    Stmt insert(db,"INSERT INTO registered_instruments(id,body) VALUES(?,?)");
    insert.text(1,id);insert.text(2,item.dump());insert.row();
    return item;
}
json Monitor::authorizeIexAsset(const std::string& symbol,const json& asset){
    std::lock_guard lock(mu);
    if(!asset.is_object()||asset.value("symbol","")!=symbol||
       asset.value("asset_class","")!="us_equity"||
       asset.value("status","")!="active")
        throw std::invalid_argument("Alpaca asset does not match active US equity");
    const auto mic=micFromAlpaca(asset.value("exchange",""));
    if(mic.empty())throw std::invalid_argument("Unsupported US listing exchange");
    Stmt old(db,"SELECT body FROM registered_instruments WHERE id=?");
    old.text(1,symbol);
    if(!old.row())throw std::invalid_argument("Register instrument first");
    auto current=json::parse(old.str(0));
    if(current.value("currency","")!="USD"||current.value("mic","")!=mic)
        throw std::invalid_argument("Alpaca asset conflicts with selected listing");
    current["source"]="alpaca-iex";
    current["verification"]="alpaca-asset-lookup; live IEX data entitlement NOT tested";
    // The broker asset-directory lookup alone does not confirm quote permission.
    sql("BEGIN IMMEDIATE");
    try{
        Stmt update(db,"UPDATE registered_instruments SET body=? WHERE id=?");
        update.text(1,current.dump());update.text(2,symbol);update.row();
        Stmt rules(db,"SELECT id,body FROM alert_rules");
        while(rules.row()){
            Rule r=load(json::parse(rules.str(1)));
            if(r.instrument!=symbol)continue;
            cancelPending(db,r.id);
            r.feed="alpaca-iex";r.venue="IEX";r.generation++;
            Stmt u(db,"UPDATE alert_rules SET body=? WHERE id=?");
            u.text(1,ruleJson(r).dump());u.text(2,r.id);u.row();
            states.erase(r.id);
        }
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
    return current;
}

json Monitor::save(const json& j){
    std::lock_guard lock(mu);
    Rule r=parseRule(j,catalogUnlocked());
    sql("BEGIN IMMEDIATE");
    try {
        if(r.id.empty()){
            Stmt s(db,"SELECT lower(hex(randomblob(16)))");s.row();r.id=s.str(0);
        }else{
            Stmt old(db,"SELECT body FROM alert_rules WHERE id=?");
            old.text(1,r.id);
            if(!old.row())throw std::invalid_argument("Unknown rule");
            r.generation=load(json::parse(old.str(0))).generation+1;
            cancelPending(db,r.id);
        }
        auto body=ruleJson(r);
        Stmt s(db,"INSERT OR REPLACE INTO alert_rules VALUES(?,?)");
        s.text(1,r.id);s.text(2,body.dump());s.row();
        sql("COMMIT");
        states.erase(r.id);
        return body;
    }catch(...){sql("ROLLBACK");throw;}
}
void Monitor::action(const std::string& id,const std::string& a){
    std::lock_guard lock(mu);
    sql("BEGIN IMMEDIATE");
    try {
        Stmt s(db,"SELECT body FROM alert_rules WHERE id=?");
        s.text(1,id);
        if(!s.row())throw std::invalid_argument("Unknown rule");
        auto r=load(json::parse(s.str(0)));
        if(a!="delete"&&a!="pause"&&a!="rearm")
            throw std::invalid_argument("Unknown action");
        cancelPending(db,id);
        if(a=="delete"){
            Stmt d(db,"DELETE FROM alert_rules WHERE id=?");
            d.text(1,id);d.row();
        }else{
            r.armed=a=="rearm";
            r.generation++;
            Stmt u(db,"UPDATE alert_rules SET body=? WHERE id=?");
            u.text(1,ruleJson(r).dump());u.text(2,id);u.row();
        }
        sql("COMMIT");
        states.erase(id);
    }catch(...){sql("ROLLBACK");throw;}
}
void Monitor::ingestIex(const json& frame,int64_t now){
    if(!frame.is_object()||!frame.contains("data")||!frame["data"].is_object())
        throw std::invalid_argument("Malformed stream frame");
    const auto& data=frame["data"];
    if(!data.contains("S")||!data["S"].is_string())
        throw std::invalid_argument("Missing instrument symbol");
    const std::string symbol=data["S"].get<std::string>();
    const std::string kind=frame.value("kind","");
    if((kind!="q"&&kind!="t")||data.value("T","")!=kind)
        throw std::invalid_argument("Unsupported stream event");
    bool found=false;
    {
        std::lock_guard lock(mu);
        for(const auto& asset:catalogUnlocked()){
            if(asset.value("id","")==symbol&&asset.value("source","")=="alpaca-iex"&&
               asset.value("currency","")=="USD"){found=true;break;}
        }
    }
    if(!found)throw std::invalid_argument("Unregistered or unverified stream instrument");
    const bool open=frame.value("marketOpen",false);
    Quote q;
    if(kind=="q"){
        q=alpacaQuote(symbol,data,now,open);
    }else{
        q.instrument=symbol;q.currency="USD";q.feed="alpaca-iex";q.venue="IEX";
        q.session=open?"open":"closed";q.receivedTime=now;q.delaySeconds=0;
        alpacaTrade(q,data);
        q.entitled=q.last.has_value(); // Never mark an unknown venue as IEX.
    }
    observe(q,now);
}
void Monitor::observe(const Quote& q,int64_t now){
    std::lock_guard lock(mu);
    // Merge separate quote/trade channels. Do not erase ASK when a new LAST
    // arrives, or overwrite a newer channel timestamp with an older message.
    {
        auto display=quoteJson(q,now);
        Stmt prior(db,"SELECT body FROM latest_quotes WHERE instrument=?");
        prior.text(1,q.instrument);
        if(prior.row()){
            const auto previous=json::parse(prior.str(0));
            if(previous.value("currency","")==q.currency&&
               previous.value("feed","")==q.feed&&previous.value("venue","")==q.venue){
                const auto oldQuote=previous.value("exchangeTime",int64_t{0});
                const auto oldQuoteNanos=previous.value("exchangeNanos",int64_t{0});
                const auto oldTrade=previous.value("lastTime",int64_t{0});
                const auto oldTradeNanos=previous.value("lastNanos",int64_t{0});
                const auto quoteOlder=q.exchangeTime==0||
                    (oldQuoteNanos>0&&q.exchangeNanos>0
                        ? oldQuoteNanos>q.exchangeNanos
                        : oldQuote>q.exchangeTime);
                const auto tradeOlder=q.lastTime==0||
                    (oldTradeNanos>0&&q.lastNanos>0
                        ? oldTradeNanos>q.lastNanos
                        : oldTrade>q.lastTime);
                if(quoteOlder){
                    for(auto key:{"askUnits","bidUnits","exchangeTime","exchangeNanos","ageSeconds"})
                        if(previous.contains(key))display[key]=previous[key];
                }
                if(tradeOlder){
                    for(auto key:{"lastUnits","lastTime","lastNanos","lastAgeSeconds"})
                        if(previous.contains(key))display[key]=previous[key];
                }
            }
        }
        Stmt u(db,"INSERT INTO latest_quotes VALUES(?,?) "
                  "ON CONFLICT(instrument) DO UPDATE SET body=excluded.body");
        u.text(1,q.instrument);u.text(2,display.dump());u.row();
    }
    health["lastReceived"]=now;
    health["instrument"]=q.instrument;
    health["exchangeTime"]=q.exchangeTime;
    health["venue"]=q.venue;health["feed"]=q.feed;
    health["session"]=q.session;health["delaySeconds"]=q.delaySeconds;
    Stmt s(db,"SELECT body FROM alert_rules");
    while(s.row()){
        auto r=load(json::parse(s.str(0)));
        if(r.instrument!=q.instrument)continue;
        auto result=evaluate(r,states[r.id],q,now);
        health["evaluation"]=result;
        if(result!="trigger")continue;
        const auto id=r.id+":"+std::to_string(r.generation);
        auto event=ruleJson(r);
        event["id"]=id;
        event["ruleId"]=r.id;
        event["observedAt"]=r.basis=="LAST"?q.lastTime:q.exchangeTime;event["receivedAt"]=now;
        event["priceUnits"]=r.basis=="ASK"?*q.ask:*q.last;
        event["delaySeconds"]=q.delaySeconds;event["session"]=q.session;
        sql("BEGIN IMMEDIATE");
        try {
            Stmt e(db,"INSERT OR IGNORE INTO alert_events VALUES(?,?)");
            e.text(1,id);e.text(2,event.dump());e.row();
            if(sqlite3_changes(db)){
                for(const auto channel:{"notification","email"}){
                    if(std::string(channel)=="email"&&r.email.empty())continue;
                    auto b=event;b["channel"]=channel;
                    Stmt o(db,"INSERT INTO delivery_outbox(id,body) VALUES(?,?)");
                    o.text(1,id+":"+channel);o.text(2,b.dump());o.row();
                }
            }
            r.armed=false;
            Stmt u(db,"UPDATE alert_rules SET body=? WHERE id=?");
            u.text(1,ruleJson(r).dump());u.text(2,r.id);u.row();
            sql("COMMIT");
        }catch(...){sql("ROLLBACK");states.erase(r.id);throw;}
    }
}
void Monitor::disconnect(const std::string& reason){
    std::lock_guard lock(mu);
    states.clear();
    health={{"status",reason}};
}
void Monitor::sourceHealth(const json& j){
    std::lock_guard lock(mu);
    // A CROSS needs two consecutive *observed* ticks. A transport outage,
    // session-clock failure or rejected subscription destroys that guarantee
    // even if a later tick arrives before maxAge expires. Preserve rules and
    // quote display but discard all crossing baselines until re-established.
    const auto status=j.is_object()?j.value("status",std::string("unknown")):"unknown";
    if(status!="subscribed"&&status!="received")states.clear();
    health=j;
}
json Monitor::claim(int64_t now,bool includeEmail){
    std::lock_guard lock(mu);
    json rows=json::array();
    sql("BEGIN IMMEDIATE");
    try {
        // The fifth attempt may expire while the app is down: do not leave it 'sending' forever.
        {
            Stmt expire(db,"UPDATE delivery_outbox SET status='failed',lease=NULL "
                           "WHERE status='sending' AND due<=? AND attempts>=5");
            expire.num(1,now);expire.row();
        }
        Stmt s(db,"SELECT id,body FROM delivery_outbox "
                  "WHERE status IN ('pending','sending') AND due<=? AND attempts<5 "
                  "AND (? OR id NOT LIKE '%:email') "
                  "ORDER BY due,rowid LIMIT 10");
        s.num(1,now);s.num(2,includeEmail?1:0);
        while(s.row()){
            const auto id=s.str(0);
            Stmt token(db,"SELECT lower(hex(randomblob(16)))");token.row();
            const auto lease=token.str(0);
            Stmt u(db,"UPDATE delivery_outbox "
                      "SET status='sending',due=?,attempts=attempts+1,lease=? WHERE id=?");
            u.num(1,now+120);u.text(2,lease);u.text(3,id);u.row();
            auto b=json::parse(s.str(1));
            b["deliveryId"]=id;b["leaseToken"]=lease;
            rows.push_back(std::move(b));
        }
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
    return rows;
}
void Monitor::complete(const std::string& id,const std::string& lease,bool ok,int64_t now){
    std::lock_guard lock(mu);
    if(lease.empty())return; // Missing leases are never allowed to acknowledge a reissued job.
    sql("BEGIN IMMEDIATE");
    try {
        Stmt s(db,"UPDATE delivery_outbox "
                  "SET status=CASE WHEN ? THEN 'accepted' "
                  "WHEN attempts>=5 THEN 'failed' ELSE 'pending' END,"
                  "due=?+(30 << min(attempts,5)),lease=NULL "
                  "WHERE id=? AND status='sending' AND lease=?");
        s.num(1,ok);s.num(2,now);s.text(3,id);s.text(4,lease);s.row();
        if(sqlite3_changes(db)){
            Stmt a(db,"INSERT INTO delivery_attempts VALUES(?,?,?)");
            a.text(1,id);a.num(2,now);a.num(3,ok);a.row();
        }
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
}
