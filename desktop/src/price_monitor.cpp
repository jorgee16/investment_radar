void Monitor::sql(const char* s){
    if(sqlite3_exec(db,s,nullptr,nullptr,nullptr)!=SQLITE_OK)
        throw std::runtime_error("Monitor transaction failed");
}
Monitor::Monitor(const std::string& path){
    if(sqlite3_open(path.c_str(),&db)!=SQLITE_OK){
        if(db)sqlite3_close(db);
        db=nullptr;
        throw std::runtime_error("Cannot open monitor database");
    }
    sqlite3_busy_timeout(db,5000);
    sql("PRAGMA journal_mode=WAL; PRAGMA synchronous=FULL;");
    Stmt version(db,"PRAGMA user_version");
    version.row();
    const int schema=sqlite3_column_int(version.p,0);
    if(schema>3)throw std::runtime_error("Monitor database requires newer application");
    sql("BEGIN IMMEDIATE");
    try {
        if(schema==0){
            sql("CREATE TABLE IF NOT EXISTS alert_rules(id TEXT PRIMARY KEY,body TEXT NOT NULL);"
                "CREATE TABLE IF NOT EXISTS alert_events(id TEXT PRIMARY KEY,body TEXT NOT NULL);"
                "CREATE TABLE IF NOT EXISTS delivery_outbox("
                "id TEXT PRIMARY KEY,body TEXT NOT NULL,attempts INTEGER NOT NULL DEFAULT 0,"
                "due INTEGER NOT NULL DEFAULT 0,status TEXT NOT NULL DEFAULT 'pending',lease TEXT);"
                "CREATE TABLE IF NOT EXISTS delivery_attempts(id TEXT,at INTEGER,accepted INTEGER);");
        }
        if(schema==1)
            sql("ALTER TABLE delivery_outbox ADD COLUMN lease TEXT;");
        sql("CREATE TABLE IF NOT EXISTS latest_quotes("
            "instrument TEXT PRIMARY KEY,body TEXT NOT NULL);"
            "CREATE TABLE IF NOT EXISTS registered_instruments(id TEXT PRIMARY KEY,body TEXT NOT NULL);"
            "PRAGMA user_version=3;");
        sql("COMMIT");
    }catch(...){sql("ROLLBACK");throw;}
}
Monitor::~Monitor(){if(db)sqlite3_close(db);}
json Monitor::catalogUnlocked(){
    json list=instruments();
    Stmt s(db,"SELECT body FROM registered_instruments ORDER BY id");
    while(s.row())list.push_back(json::parse(s.str(0)));
    return list;
}
json Monitor::snapshot(){
    std::lock_guard lock(mu);
    json j={{"health",health},{"instruments",catalogUnlocked()},{"rules",json::array()},
            {"events",json::array()},{"deliveries",json::array()},
            {"quotes",json::array()}};
    for(auto table:{"alert_rules","alert_events","latest_quotes"}){
        std::string query="SELECT body FROM "+std::string(table)+" ORDER BY rowid DESC LIMIT 200";
        Stmt s(db,query.c_str());
        const char* key=std::string(table)=="alert_rules"?"rules":
                        std::string(table)=="alert_events"?"events":"quotes";
        while(s.row()){
            auto b=json::parse(s.str(0));
            if(std::string(table)=="latest_quotes"){
                const auto stamp=b.value("exchangeTime",int64_t{0});
                b["ageSeconds"]=stamp>0?json(std::time(nullptr)-stamp):json(nullptr);
                const auto lastStamp=b.value("lastTime",int64_t{0});
                b["lastAgeSeconds"]=lastStamp>0?json(std::time(nullptr)-lastStamp):json(nullptr);
            }
            j[key].push_back(b);
        }
    }
    Stmt d(db,"SELECT id,status,attempts FROM delivery_outbox ORDER BY rowid DESC LIMIT 100");
    while(d.row())j["deliveries"].push_back(
        {{"id",d.str(0)},{"status",d.str(1)},{"attempts",sqlite3_column_int(d.p,2)}});
    return j;
}
