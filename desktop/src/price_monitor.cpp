struct Stmt {
    sqlite3_stmt* p=nullptr;
    Stmt(sqlite3* db,const char* sql) {
        if(sqlite3_prepare_v2(db,sql,-1,&p,nullptr)!=SQLITE_OK)
            throw std::runtime_error("Monitor statement failed");
    }
    ~Stmt(){sqlite3_finalize(p);}
    void text(int n,const std::string& s){sqlite3_bind_text(p,n,s.c_str(),-1,SQLITE_TRANSIENT);}
    void num(int n,int64_t v){sqlite3_bind_int64(p,n,v);}
    bool row(){
        const int rc=sqlite3_step(p);
        if(rc!=SQLITE_ROW&&rc!=SQLITE_DONE)throw std::runtime_error("Monitor storage failed");
        return rc==SQLITE_ROW;
    }
    std::string str(int n){
        auto* v=sqlite3_column_text(p,n);
        return v?reinterpret_cast<const char*>(v):std::string();
    }
};
Rule load(const json& j){
    Rule r;
    r.id=j.at("id");r.instrument=j.at("instrument");r.currency=j.at("currency");
    r.venue=j.at("venue");r.feed=j.at("feed");r.basis=j.at("basis");
    r.mode=j.at("mode");r.target=j.at("targetUnits");r.maxAge=j.at("maxAge");
    r.armed=j.at("armed");r.generation=j.at("generation");r.email=j.at("email");
    return r;
}
void cancelPending(sqlite3* db,const std::string& ruleId){
    // UUIDs are generated by SQLite and contain no LIKE metacharacters.
    Stmt s(db,"UPDATE delivery_outbox SET status='cancelled',lease=NULL "
              "WHERE id LIKE ? AND status IN ('pending','sending')");
    s.text(1,ruleId+":%");
    s.row();
}
json quoteJson(const Quote& q,int64_t now){
    return {
        {"instrument",q.instrument},{"currency",q.currency},{"venue",q.venue},
        {"feed",q.feed},{"session",q.session},
        {"askUnits",q.ask?json(*q.ask):json(nullptr)},
        {"bidUnits",q.bid?json(*q.bid):json(nullptr)},
        {"lastUnits",q.last?json(*q.last):json(nullptr)},
        {"exchangeTime",q.exchangeTime},{"exchangeNanos",q.exchangeNanos},
        {"lastTime",q.lastTime},{"lastNanos",q.lastNanos},{"receivedTime",q.receivedTime},
        {"ageSeconds",q.exchangeTime>0?json(now-q.exchangeTime):json(nullptr)},
        {"lastAgeSeconds",q.lastTime>0?json(now-q.lastTime):json(nullptr)},
        {"entitled",q.entitled},{"demo",q.demo},{"delaySeconds",q.delaySeconds}
    };
}
